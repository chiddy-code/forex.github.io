function load_article_page() {
    let url = new URLSearchParams(window.location.search)
    let id_check = url.has('id')
    let id = url.get('id')
    let m = document.querySelector('.article')
    if (id_check) {
        if (id == null || isNaN(Number(id))) {
            document.body.innerHTML = "Error: Forbidden Entry"
        } else {
            let found_id = false
            for (const article of articles.published) {
                if (article.id == id) {
                    document.title = article.title.trim()
                    m.innerHTML = get_article_layout(article.image, article.title, article.genre, article.Intro, article.content, article.view_count)
                    found_id = true
                    break
                } else {
                    m.innerHTML = "loading article...."
                }
            }
            if (!found_id) {
                document.body.innerHTML = "Article does not exist!! 404 Not Found"
            }
        }
    } else {
        document.body.innerHTML = "Error: Forbidden Entry"
    }
}

