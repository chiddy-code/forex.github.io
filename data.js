function sortNumArray(numArray) {
    let n = []
    for (let index = 0; index < numArray.length; index++) {
        let largest = 0
        for (const y of numArray) {
            if (!n.includes(y)) {
                if (y > largest) {
                    largest = y
                }
            }
        }
        n.push(largest)
    }
    return n
}

